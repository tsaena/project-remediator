"""Deterministic, non-executing remediation plans for pinned Python requirements.

``plan(scan)`` is a pure function: no I/O, network, or subprocesses. A proposal
is made only when every advisory for a dependency agrees on a fixed version
and that version is checked against every advisory's own ranges. Everything
else is an explicit refusal with a reason. A plan never edits files and never
claims that an upgrade exists, installs, or works.

Developer CLI: python -m remediator.planning REPORT.json [--output PLAN.json]
"""

import argparse
import os
import posixpath
import sys
from collections.abc import Iterable
from datetime import datetime
from enum import StrEnum
from pathlib import Path
from typing import Literal, Self

from packaging.version import InvalidVersion, Version
from pydantic import Field, ValidationError, model_validator

from remediator.correlation import (
    AdvisoryGroup,
    ComponentSlot,
    GroupRisk,
    ScanGroups,
    manifest_path,
)
from remediator.domain import (
    AdvisorySource,
    Asset,
    CoverageStatus,
    FixApplicability,
    PackageCoverage,
    Scanner,
    ScanResult,
    ScanStatus,
)
from remediator.domain.models import DomainModel, NonBlank
from remediator.fixes import (
    ECOSYSTEM,
    GroupFix,
    GroupFixStatus,
    evaluate_fix,
    group_fix,
)
from remediator.naming import canonical_pypi_name
from remediator.output import private_output

PLAN_SCHEMA_VERSION: Literal[1] = 1
# Reports are local files written by this project; bound them anyway.
MAX_REPORT_BYTES = 64 * 1024 * 1024
# Lockfiles are exact but regenerated by tools, never edited by hand.
LOCKFILES = frozenset({"Pipfile.lock", "pdm.lock", "poetry.lock", "uv.lock"})


class PlanDecision(StrEnum):
    PROPOSED = "proposed"
    REFUSED = "refused"


class RefusalReason(StrEnum):
    SCAN_NOT_SUCCESSFUL = "scan_not_successful"
    SLOT_UNAVAILABLE = "slot_unavailable"
    UNSUPPORTED_ECOSYSTEM = "unsupported_ecosystem"
    MULTIPLE_INSTALLED_VERSIONS = "multiple_installed_versions"
    UNSUPPORTED_MANIFEST = "unsupported_manifest"
    VERSION_UNCONFIRMED = "version_unconfirmed"
    INCONSISTENT_EVIDENCE = "inconsistent_evidence"
    CONFLICTING_ADVISORIES = "conflicting_advisories"
    NO_FIX_CANDIDATE = "no_fix_candidate"
    TARGET_NOT_NEWER = "target_not_newer"
    TARGET_STILL_AFFECTED = "target_still_affected"
    TARGET_UNVERIFIABLE = "target_unverifiable"


class PlanUnknown(StrEnum):
    """What a proposal does not establish; always listed explicitly."""

    RELEASE_EXISTENCE = "release_existence"
    INSTALLABILITY = "installability"
    DEPENDENCY_RESOLUTION = "dependency_resolution"
    COMPATIBILITY = "compatibility"
    TRANSITIVE_DEPENDENCIES = "transitive_dependencies"
    REQUIREMENT_HASHES = "requirement_hashes"


UNKNOWNS = list(PlanUnknown)


class PlanLimitationReason(StrEnum):
    SCAN_NOT_SUCCESSFUL = "scan_not_successful"
    COVERAGE_MISSING = "coverage_missing"
    COVERAGE_INCOMPLETE = "coverage_incomplete"
    COVERAGE_UNKNOWN = "coverage_unknown"
    MISSING_ASSET_KEY = "missing_asset_key"


class PlanLimitation(DomainModel):
    reason: PlanLimitationReason
    detail: NonBlank


class ScanReference(DomainModel):
    """Which scan a plan came from, so verification can check comparability."""

    execution_id: NonBlank
    asset: Asset
    scanner: Scanner
    status: ScanStatus
    coverage_status: CoverageStatus | None = None
    advisory_source: AdvisorySource | None = None
    started_at: datetime | None = None
    finished_at: datetime | None = None


class PlannedChange(DomainModel):
    """A proposed requirement change. Nothing is edited by planning."""

    manifest_path: NonBlank
    package: NonBlank
    current_version: NonBlank
    proposed_version: NonBlank
    requirement: NonBlank
    # A reviewer's cue: candidates can be large jumps (e.g. Django 3.2 -> 5.2).
    crosses_major_version: bool


class PlanGroup(DomainModel):
    """One advisory alias group and its combined fix evidence."""

    identifiers: list[NonBlank] = Field(min_length=1)
    risks: list[GroupRisk] = Field(default_factory=list)
    fix: GroupFix


class PlanEntry(DomainModel):
    slot: ComponentSlot | None = None
    ecosystem: NonBlank
    package: NonBlank
    manifest_path: NonBlank | None = None
    installed_versions: list[NonBlank] = Field(min_length=1)
    decision: PlanDecision
    change: PlannedChange | None = None
    refusal: RefusalReason | None = None
    detail: NonBlank
    groups: list[PlanGroup] = Field(min_length=1)
    unknowns: list[PlanUnknown] = Field(default_factory=list)

    @model_validator(mode="after")
    def validate_decision(self) -> Self:
        if self.decision == PlanDecision.REFUSED:
            if self.change is not None or self.refusal is None:
                raise ValueError("a refusal has a reason and no change")
            return self
        change = self.change
        if change is None or self.refusal is not None or self.slot is None:
            raise ValueError("a proposal needs a slot and a change, not a refusal")
        if set(self.unknowns) != set(PlanUnknown):
            raise ValueError("a proposal lists every unknown")
        if any(g.fix.status != GroupFixStatus.CANDIDATE for g in self.groups):
            raise ValueError("a proposal needs a candidate for every group")
        candidates = [Version(g.fix.fixed_version or "") for g in self.groups]
        proposed = Version(change.proposed_version)
        if proposed != max(candidates):
            raise ValueError("the proposed version must be the highest candidate")
        if self.installed_versions != [change.current_version] or proposed <= Version(
            change.current_version
        ):
            raise ValueError("a proposal upgrades the single installed version")
        if change.crosses_major_version != (
            proposed.major != Version(change.current_version).major
        ):
            raise ValueError("crosses_major_version must match the versions")
        return self


class RemediationPlan(DomainModel):
    plan_schema_version: Literal[1] = PLAN_SCHEMA_VERSION
    source: ScanReference
    limitations: list[PlanLimitation] = Field(default_factory=list)
    entries: list[PlanEntry] = Field(default_factory=list)

    @model_validator(mode="after")
    def validate_source(self) -> Self:
        unsuccessful = self.source.status != ScanStatus.SUCCESS
        noted = any(
            n.reason == PlanLimitationReason.SCAN_NOT_SUCCESSFUL
            for n in self.limitations
        )
        if unsuccessful != noted:
            raise ValueError("an unsuccessful scan must be a plan limitation")
        if unsuccessful and any(
            e.decision == PlanDecision.PROPOSED for e in self.entries
        ):
            raise ValueError("an unsuccessful scan cannot produce proposals")
        return self


def _is_requirements_file(path: str) -> bool:
    # The same rule OSV-Scanner applies: *requirements*.txt, case-sensitive.
    name = posixpath.basename(path)
    return name not in LOCKFILES and name.endswith(".txt") and "requirements" in name


def _package_coverage(
    scan: ScanResult, slot: ComponentSlot, version: str
) -> PackageCoverage | None:
    if scan.coverage is None:
        return None
    for manifest in scan.coverage.manifests:
        if manifest_path(manifest.path, scan.asset.locator) != slot.manifest_path:
            continue
        for package in manifest.packages:
            if (
                package.ecosystem == slot.ecosystem
                and canonical_pypi_name(package.name) == slot.name
                and package.version == version
            ):
                return package
    return None


class _Refused(Exception):
    def __init__(self, reason: RefusalReason, detail: str) -> None:
        super().__init__(detail)
        self.reason = reason
        self.detail = detail


def _plan_groups(groups: list[AdvisoryGroup], scan: ScanResult) -> list[PlanGroup]:
    return [
        PlanGroup(identifiers=g.identifiers, risks=g.risks, fix=group_fix(g, scan))
        for g in groups
    ]


def _check_evidence(scan: ScanResult, indices: Iterable[int], version: str) -> None:
    """Recompute each finding's fix from its advisory ranges; reports are input."""
    for index in indices:
        finding = scan.findings[index]
        if finding.fix.evidence is None:
            raise _Refused(
                RefusalReason.NO_FIX_CANDIDATE,
                f"{finding.vulnerability.primary_id} carries no fix evidence",
            )
        listed = finding.fix.evidence.listed_in_versions
        expected = evaluate_fix(
            finding.vulnerability.affected,
            ecosystem=finding.component.ecosystem,
            name=finding.component.name,
            installed_version=version,
            version_confirmed=True,
            listed_in_versions=listed,
        )
        if expected != finding.fix:
            raise _Refused(
                RefusalReason.INCONSISTENT_EVIDENCE,
                f"recorded fix for {finding.vulnerability.primary_id} does not match "
                "its advisory ranges",
            )


def _target(
    scan: ScanResult, indices: list[int], plan_groups: list[PlanGroup], current: str
) -> str:
    statuses = [g.fix.status for g in plan_groups]
    if GroupFixStatus.CONFLICT in statuses:
        raise _Refused(
            RefusalReason.CONFLICTING_ADVISORIES,
            "advisories in at least one group disagree on a fixed version",
        )
    if GroupFixStatus.UNKNOWN in statuses:
        raise _Refused(
            RefusalReason.NO_FIX_CANDIDATE,
            f"{statuses.count(GroupFixStatus.UNKNOWN)} of {len(statuses)} advisory "
            "groups have no supported fixed version",
        )
    spellings = [g.fix.fixed_version for g in plan_groups if g.fix.fixed_version]
    try:
        highest = max(Version(s) for s in spellings)
        installed = Version(current)
    except InvalidVersion as invalid:
        raise _Refused(RefusalReason.TARGET_UNVERIFIABLE, str(invalid)) from None
    # PEP 440-equal spellings: report one deterministically.
    target = min(s for s in spellings if Version(s) == highest)
    if highest <= installed:
        raise _Refused(
            RefusalReason.TARGET_NOT_NEWER,
            f"candidate {target} is not newer than the installed {current}",
        )
    # The highest candidate must lie outside every range of every advisory.
    for index in indices:
        finding = scan.findings[index]
        check = evaluate_fix(
            finding.vulnerability.affected,
            ecosystem=finding.component.ecosystem,
            name=finding.component.name,
            installed_version=target,
            version_confirmed=True,
            listed_in_versions=None,
        )
        applicability = check.evidence.applicability if check.evidence else None
        if applicability == FixApplicability.AFFECTED:
            raise _Refused(
                RefusalReason.TARGET_STILL_AFFECTED,
                f"{finding.vulnerability.primary_id} still affects {target}",
            )
        if applicability != FixApplicability.NOT_AFFECTED:
            raise _Refused(
                RefusalReason.TARGET_UNVERIFIABLE,
                f"cannot confirm that {finding.vulnerability.primary_id} spares "
                f"{target}",
            )
    return target


def _entry(
    scan: ScanResult,
    slot: ComponentSlot | None,
    groups: list[AdvisoryGroup],
    duplicate: bool,
) -> PlanEntry:
    indices = sorted({o.finding_index for g in groups for o in g.observations})
    first = scan.findings[indices[0]].component
    versions = sorted({o.installed_version for g in groups for o in g.observations})
    plan_groups = _plan_groups(groups, scan)

    def entry(decision: PlanDecision, detail: str, **result: object) -> PlanEntry:
        return PlanEntry.model_validate(
            {
                "slot": slot,
                "ecosystem": first.ecosystem,
                "package": first.name,
                "manifest_path": slot.manifest_path if slot else None,
                "installed_versions": versions,
                "groups": plan_groups,
                "decision": decision,
                "detail": detail,
                **result,
            }
        )

    try:
        if scan.status != ScanStatus.SUCCESS:
            raise _Refused(
                RefusalReason.SCAN_NOT_SUCCESSFUL,
                f"the scan is {scan.status.value}",
            )
        if slot is None:
            raise _Refused(
                RefusalReason.SLOT_UNAVAILABLE,
                "the finding's manifest is not within the scanned asset",
            )
        if slot.ecosystem != ECOSYSTEM:
            raise _Refused(
                RefusalReason.UNSUPPORTED_ECOSYSTEM,
                f"planning supports {ECOSYSTEM} only",
            )
        if duplicate or len(versions) != 1:
            raise _Refused(
                RefusalReason.MULTIPLE_INSTALLED_VERSIONS,
                "the manifest declares several versions of this package",
            )
        if not _is_requirements_file(slot.manifest_path):
            raise _Refused(
                RefusalReason.UNSUPPORTED_MANIFEST,
                "only *requirements*.txt pins are planned; lockfiles and other "
                "manifests are not edited",
            )
        [current] = versions
        coverage = _package_coverage(scan, slot, current)
        if coverage is None or not coverage.confidently_assessed:
            raise _Refused(
                RefusalReason.VERSION_UNCONFIRMED,
                "coverage does not confirm an exact pin for the installed version",
            )
        _check_evidence(scan, indices, current)
        target = _target(scan, indices, plan_groups, current)
    except _Refused as refused:
        return entry(PlanDecision.REFUSED, refused.detail, refusal=refused.reason)
    return entry(
        PlanDecision.PROPOSED,
        f"every advisory group reports a fix at or below {target}, and no "
        "advisory range contains it; not proof that it exists, installs, or works",
        change=PlannedChange(
            manifest_path=slot.manifest_path,
            package=first.name,
            current_version=current,
            proposed_version=target,
            requirement=f"{first.name}=={target}",
            crosses_major_version=Version(target).major != Version(current).major,
        ),
        unknowns=UNKNOWNS,
    )


def _limitations(scan: ScanResult) -> list[PlanLimitation]:
    notes = []
    if scan.status != ScanStatus.SUCCESS:
        notes.append(
            PlanLimitation(
                reason=PlanLimitationReason.SCAN_NOT_SUCCESSFUL,
                detail=f"the scan is {scan.status.value}; findings may be missing "
                "and nothing is proposed",
            )
        )
    if scan.coverage is None:
        notes.append(
            PlanLimitation(
                reason=PlanLimitationReason.COVERAGE_MISSING,
                detail="the report has no coverage; unassessed packages are unknown",
            )
        )
    elif scan.coverage.status == CoverageStatus.INCOMPLETE:
        notes.append(
            PlanLimitation(
                reason=PlanLimitationReason.COVERAGE_INCOMPLETE,
                detail="some packages were not confidently assessed; they may be "
                "vulnerable and are not planned",
            )
        )
    elif scan.coverage.status != CoverageStatus.NO_KNOWN_GAPS:
        notes.append(
            PlanLimitation(
                reason=PlanLimitationReason.COVERAGE_UNKNOWN,
                detail=f"coverage is {scan.coverage.status.value}",
            )
        )
    if scan.asset.key is None:
        notes.append(
            PlanLimitation(
                reason=PlanLimitationReason.MISSING_ASSET_KEY,
                detail="slots use the scan locator, which is not a stable identity; "
                "verification will need an asset key",
            )
        )
    return notes


def plan(scan: ScanResult) -> RemediationPlan:
    """A deterministic plan for one scan; refusals are explicit, never omitted."""
    groups = ScanGroups(scan, scan.asset.key or scan.asset.locator)
    entries = [
        _entry(scan, slot, slot_groups, slot in groups.duplicates)
        for slot, slot_groups in sorted(
            groups.groups.items(),
            key=lambda item: (
                item[0].ecosystem,
                item[0].name,
                item[0].manifest_path,
            ),
        )
    ]
    entries += [_entry(scan, None, [group], False) for group in groups.unplaced]
    provenance = scan.provenance
    return RemediationPlan(
        source=ScanReference(
            execution_id=scan.execution_id,
            asset=scan.asset,
            scanner=scan.scanner,
            status=scan.status,
            coverage_status=scan.coverage.status if scan.coverage else None,
            advisory_source=provenance.advisory_source if provenance else None,
            started_at=provenance.started_at if provenance else None,
            finished_at=provenance.finished_at if provenance else None,
        ),
        limitations=_limitations(scan),
        entries=entries,
    )


def _read_report(path: Path) -> bytes:
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
    with os.fdopen(fd, "rb") as handle:
        data = handle.read(MAX_REPORT_BYTES + 1)
    if len(data) > MAX_REPORT_BYTES:
        raise ValueError(f"report exceeds {MAX_REPORT_BYTES} bytes")
    return data


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Plan remediation for a normalized scan report. Nothing is "
        "edited; proposals are evidence, not proof."
    )
    parser.add_argument("report", type=Path)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args(argv)
    try:
        scan = ScanResult.model_validate_json(_read_report(args.report))
        rendered = plan(scan).model_dump_json(indent=2) + "\n"
        if args.output is None:
            sys.stdout.write(rendered)
        else:
            output = Path(os.path.abspath(args.output))
            if output == Path(os.path.abspath(args.report)):
                raise ValueError("output must differ from the report")
            with private_output(output) as handle:
                handle.write(rendered.encode())
    except (OSError, ValueError, ValidationError) as exc:
        parser.error(f"planning failed: {exc}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
